const SPECIAL = {
  EUR: "eu",
  USD: "us",
  GBP: "gb",
  INR: "in",
  CHF: "ch",
  XOF: "sn",
  XAF: "cm",
  XPF: "pf",
  XCD: "ag",
  TRY: "tr",
  KPW: "kp",
  LAK: "la",
  MKD: "mk",
};

const lowerMap = Object.fromEntries(
  Object.entries(NAME_TO_ISO).map(([k, v]) => [k.toLowerCase(), v])
);

const out = {};
const miss = [];
for (const row of cc.data) {
  if (Object.prototype.hasOwnProperty.call(SPECIAL, row.code)) {
    out[row.code] = SPECIAL[row.code];
    continue;
  }
  const countries = row.countries || [];
  let iso = null;
  const preferred = PREFER[row.code];
  if (preferred) {
    iso = NAME_TO_ISO[preferred] || lowerMap[preferred.toLowerCase()];
  }
  if (!iso) {
    for (const name of countries) {
      iso = NAME_TO_ISO[name] || lowerMap[name.toLowerCase()];
      if (iso) break;
    }
  }
  if (iso) out[row.code] = iso;
  else miss.push([row.code, countries[0] || ""]);
}

console.log("mapped", Object.keys(out).length, "miss", miss.length);
